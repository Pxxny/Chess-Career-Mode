import { endDay } from "../src/game/training/engine.ts";
import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { createNewSave } from "../src/game/createNewSave.ts";
import { createCareerRecord } from "../src/game/career/createCareer.ts";
import { randomAppearance } from "../src/data/appearance.ts";
import { captureHighlights, highlightsOf, acknowledgeArticle, highlightsSchema } from "../src/game/career/highlights.ts";
import { newSeason, runSeason, seasonOf, type SeasonPort } from "../src/game/career/seasonSimulation.ts";
import { createBackup, parseBackup } from "../src/store/backup.ts";
import { buildCareerWorld } from "../src/game/npc/buildCareerWorld.ts";
import { careerSchedule } from "../src/game/career/planning.ts";
import { registerForEvent } from "../src/game/match/registration.ts";
import { bookedStart, dayStamp } from "../src/game/competition/agenda.ts";
const options = { name: "News QA", gender: "undisclosed" as const, countryCode: "TH", city: { name: "Bangkok", custom: false }, archetype: "balanced" as const, appearance: randomAppearance(), startYear: 2026, alternateHistory: false, playerDatabase: "small" as const };
const base = createNewSave(options, createCareerRecord(options));
const winner = structuredClone(base);
winner.history.tournaments.push({ tournamentId: "qa-open", name: "Bangkok Open", rank: 1, year: 2026, week: 1, fieldSize: 12, points: 6, level: "local" });
let news = captureHighlights(base, winner);
assert.equal(highlightsOf(news).unread.length, 1);
assert(highlightsOf(news).items[0].headline.includes("Bangkok Open"));
assert.equal(captureHighlights(base, news).highlights!.items.length, 1);
news = acknowledgeArticle(news, news.highlights!.unread[0]);
assert.equal(highlightsOf(news).unread.length, 0);
assert.equal(captureHighlights(base, JSON.parse(JSON.stringify(news))).highlights!.unread.length, 0);
assert.equal(highlightsOf(captureHighlights(base, base)).items.length, 0);
const routine = structuredClone(base); routine.player.money += 100; routine.player.rating += 15;
assert.equal(highlightsOf(captureHighlights(base, routine)).items.length, 0);
const loss = structuredClone(winner); loss.history.tournaments[0].rank = 2;
assert.equal(highlightsOf(captureHighlights(base, loss)).items.length, 0);
const title = structuredClone(base); title.history.titles.push({ title: "CM", year: 2026, week: 1 });
assert.equal(highlightsOf(captureHighlights(base, title)).items[0].kind, "title");
const qualified = structuredClone(base); qualified.competition!.qualifications.push({ kind: "candidates", source: "World Cup", year: 2026 });
assert.equal(highlightsOf(captureHighlights(base, qualified)).items[0].kind, "qualification");
assert(highlightsOf(captureHighlights(base, qualified)).items[0].headline.includes("Candidates"));
// Stop on the exact committed action, before another simulated day; pending articles survive reload.
let save = { ...base, seasonSimulation: { ...newSeason(base), phase: "end-day" as const } }, advances = 0;
const port: SeasonPort = { read: () => save, npcs: () => [], commit: (next) => { save = next; }, cancelled: () => false, yield: async () => {}, play: async () => { throw new Error("unexpected game"); }, finish: () => false,
 advanceDay: async () => { advances++; save = { ...save, world: { ...save.world, day: save.world.day + 1 }, history: { ...save.history, tournaments: winner.history.tournaments } }; } };
await runSeason(port);
assert.equal(advances, 1);
assert.equal(seasonOf(save)?.status, "paused");
assert.equal(highlightsOf(save).unread.length, 1);
await runSeason(port); assert.equal(advances, 1);
save = JSON.parse(JSON.stringify(save)); await runSeason(port); assert.equal(advances, 1);
const world = buildCareerWorld(base.career);
const backup = await createBackup(save, world), restored = await parseBackup(JSON.stringify(backup));
assert.deepEqual(restored.payload.save.highlights, save.highlights);
const malformed = structuredClone(save);
(malformed.highlights!.items[0] as any).kind = "invalid-category";
const invalidBackup = await createBackup(malformed, world);
await assert.rejects(() => parseBackup(JSON.stringify(invalidBackup)));
assert.equal(highlightsSchema.safeParse({ items: [{ id: "bad" }], unread: [], seen: [] }).success, false);
// A registered national event with a real starting-roster selection interrupts BEFORE the cup plays.
let national = structuredClone(base);
national.player.rating = national.player.peakRating = 3000;
national.player.reputation = 100; national.player.league = "legendary";
national.expansion!.membershipYear = 2026;
national.world.date.week = 20;
const event = careerSchedule(national, 52).find((e) => e.details?.format === "team" && e.name.includes("Olympiad (Open)"))!;
assert(event);
const entry = registerForEvent(national, event, world); assert(entry.ok);
const stamp = dayStamp(bookedStart(event));
national = { ...entry.save, world: { ...entry.save.world, date: { year: stamp.year, week: stamp.week }, day: stamp.day } };
const callup = captureHighlights(national, national, world);
assert(highlightsOf(callup).items.some((a) => a.kind === "national"));
assert.equal(callup.expansion!.cups.length, 0);
assert.equal(captureHighlights(callup, callup, world).highlights!.items.length, 1);
writeFileSync("/tmp/chess-news-national-backup.json", JSON.stringify(await createBackup(national, world)));
const articleSave = captureHighlights(base, winner);
articleSave.seasonSimulation = newSeason(articleSave);
writeFileSync("/tmp/chess-news-victory-backup.json", JSON.stringify(await createBackup(articleSave, world)));
const yearEnd = structuredClone(articleSave);
yearEnd.world.date.week = 52; yearEnd.world.day = 7;
const rolled = endDay(yearEnd).save;
rolled.seasonSimulation = { ...yearEnd.seasonSimulation!, status: "completed", days: 364 };
writeFileSync("/tmp/chess-news-yearend-backup.json", JSON.stringify(await createBackup(rolled, world)));
console.log("PASS: wins, national starting-roster selection, titles, qualifications, routine-event suppression, exact pause boundary, reload deduplication, unread gate, backup and Zod validation.");
