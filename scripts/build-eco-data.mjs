// Builds src/data/chess/eco/ecoData.ts from the Lichess chess-openings TSV files (CC0 / public domain).
// Usage: node scripts/build-eco-data.mjs <folder with a.tsv ... e.tsv>
//   git clone --depth 1 https://github.com/lichess-org/chess-openings.git && node scripts/build-eco-data.mjs chess-openings
// The result is committed, so normal builds never need this script.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) {
  console.error('Pass the folder that holds a.tsv to e.tsv');
  process.exit(1);
}

const rows = [];
for (const letter of 'abcde') {
  const text = readFileSync(join(dir, `${letter}.tsv`), 'utf8').split(/\r?\n/);
  for (const line of text.slice(1)) {
    if (!line.trim()) continue;
    const [eco, name, pgn] = line.split('\t');
    if (!/^[A-E]\d\d$/.test(eco) || !name || !pgn) throw new Error(`Bad row: ${line}`);
    if (/[|`\\]|\$\{/.test(name)) throw new Error(`Unsafe characters in ${name}`);
    const moves = pgn.replace(/\d+\.(\.\.)?/g, ' ').trim().split(/\s+/).join(' ');
    rows.push(`${eco}|${name}|${moves}`);
  }
}
rows.sort();
const out = `// Generated by scripts/build-eco-data.mjs from github.com/lichess-org/chess-openings (CC0 1.0, public domain).
// One opening per line: ECO|name|moves in standard algebraic notation. ${rows.length} lines covering every ECO code A00 to E99.
export const ECO_DATA = \`${rows.join('\n')}\`;
`;
writeFileSync(new URL('../src/data/chess/eco/ecoData.ts', import.meta.url), out);
console.log(`Wrote ${rows.length} openings.`);
